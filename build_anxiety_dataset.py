# SELF-TEST - verifies every calculation without the restricted data
# =============================================================================

def selftest():
    """Check each computation against synthetic inputs with known answers."""
    failures = []

    def check(name, got, want, tol=1e-9):
        ok = abs(got - want) < tol if isinstance(want, float) else got == want
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}")
        if not ok:
            failures.append(f"{name}: got {got!r}, expected {want!r}")

    print("Self-test: verifying calculations against synthetic inputs\n")

    # -- 1. Percentage measure: 100 * (25 + 15) / 200 = 20.0 --------------
    print("Sociodemographic measures")
    acs = pd.DataFrame({"B15003_017E": [25.0], "B15003_018E": [15.0],
                        "B15003_001E": [200.0]})
    got = compute_measure(acs, MEASURES["Education"]["High school diploma or GED (%)"])
    check("percentage measure = 100 * sum(numerator) / denominator", got.iloc[0], 20.0)

    # -- 2. Direct estimate passes through unchanged ----------------------
    acs = pd.DataFrame({"B19013_001E": [61234.0]})
    got = compute_measure(acs, MEASURES["Income & socioeconomic"]["Median household income ($)"])
    check("direct estimate returned unchanged", got.iloc[0], 61234.0)

    # -- 3. Zero denominator yields missing, not an error -----------------
    acs = pd.DataFrame({"B03002_003E": [10.0], "B03002_001E": [0.0]})
    got = compute_measure(acs, MEASURES["Demographic"]["White alone, not Hispanic/Latino (%)"])
    check("zero denominator yields missing", bool(np.isnan(got.iloc[0])), True)

    # -- 4. Census special values recoded as missing ----------------------
    raw = pd.Series([-666666666, 42.0])
    cleaned = raw.where(~raw.isin(CENSUS_NULL))
    check("Census special value recoded as missing", bool(np.isnan(cleaned.iloc[0])), True)
    check("valid estimate preserved", cleaned.iloc[1], 42.0)

    # -- 5. Adult population is 38 cells covering ages 18+ ----------------
    print("\nCertification rate")
    check("adult population uses 38 B01001 cells", len(ADULT_POP_VARS), 38)
    check("first male cell is 18-19 years", ADULT_POP_VARS[0], "B01001_007E")
    check("first female cell is 18-19 years", ADULT_POP_VARS[19], "B01001_031E")

    # -- 6. Rate: 250 certifications / 50,000 adults * 1,000 = 5.0 --------
    merged = pd.DataFrame({"cert_count": [250, 7], "adult_pop": [50000.0, 0.0]})
    rate = np.where(merged["adult_pop"] > 0,
                    merged["cert_count"] / merged["adult_pop"] * RATE_PER, np.nan)
    check("rate = 1,000 * certifications / adult population", float(rate[0]), 5.0)
    check("zero population yields missing rate", bool(np.isnan(rate[1])), True)

    # -- 7. ZIP-to-county allocation --------------------------------------
    # ZIP 11111 lies wholly in county 42001 (100 certifications).
    # ZIP 22222 straddles 42001 and 42003 with HUD ratios 0.6 / 0.2 that do not
    # sum to 1; after renormalization (0.75 / 0.25) its 40 certifications split
    # 30 / 10. County 42001 therefore receives 100 + 30 = 130.
    print("\nZIP-to-county allocation")
    cert_long = pd.DataFrame({
        "cert_id": list(range(140)),
        "Zipcode": ["11111"] * 100 + ["22222"] * 40,
        "condition": ["Anxiety Disorders"] * 140,
    })
    hud = pd.DataFrame({
        "zip": ["11111", "22222", "22222"],
        "county": ["42001", "42001", "42003"],
        "res_ratio": [1.0, 0.6, 0.2],
    })
