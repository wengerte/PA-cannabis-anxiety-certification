def sheet_name(measure_label):
    """Excel sheet name for a measure: drop units, keep alphanumerics, cap at 31."""
    stripped = re.sub(r"\([^)]*\)", "", measure_label)
    stripped = re.sub(r"[^A-Za-z0-9 ]", "", stripped)
    return "_".join(p for p in stripped.split() if p)[:31]


def build_dataset(data_dir, api_key, years, primary_year, condition=CONDITION):
    """Run the full analysis and return (stats_df, long_df, per_measure_sheets)."""
    measures = [(domain, label) for domain, m in MEASURES.items() for label in m]
    var_ids = required_acs_vars()

    print(f"Condition:     {condition}")
    print(f"Study years:   {years[0]}-{years[-1]}  (primary year {primary_year})")
    print(f"Measures:      {len(measures)}")
    print(f"ACS variables: {len(var_ids)}\n")

    # ---- Load every year once -------------------------------------------
    acs_by_year, certs_by_year = {}, {}
    session = requests.Session()
    for year in years:
        print(f"  {year}: ACS ...", end="", flush=True)
        acs_by_year[year] = fetch_acs(year, api_key, var_ids, session=session)

        cert_long = load_certifications(os.path.join(data_dir,
                                                     f"certifications({year}).csv"))
        hud = load_hud(os.path.join(data_dir, f"PA_HUD_ZIP_COUNTY_{year}.csv"))
        certs_by_year[year] = county_cert_counts(cert_long, hud, condition)

        total = int(certs_by_year[year]["cert_count"].sum())
        print(f" {len(acs_by_year[year])} counties   certifications {total:,}")

    # ---- Compute every measure in every year ----------------------------
    stats_rows, long_rows, per_measure = [], [], {}

    for domain, label in measures:
        cfg = MEASURES[domain][label]

        for year in years:
            acs = acs_by_year[year].copy()
            acs[label] = compute_measure(acs, cfg)

            merged = acs[["county_fips", "county_name", "adult_pop", label]].merge(
                certs_by_year[year], on="county_fips", how="left")
            merged["cert_count"] = merged["cert_count"].fillna(0).astype(int)
            merged["cert_rate"] = np.where(
                merged["adult_pop"] > 0,
                merged["cert_count"] / merged["adult_pop"] * RATE_PER,
                np.nan,
            )

            valid = merged.dropna(subset=[label, "cert_rate"]).copy()
            st = compute_stats(valid[label].to_numpy(),
                               valid["cert_rate"].to_numpy())

            if st is not None:
                stats_rows.append({
                    "domain": domain,
                    "measure": label,
                    "year": year,
                    "n_counties": st["n"],
                    "total_certs": int(certs_by_year[year]["cert_count"].sum()),
                    "pearson_r": st["pearson_r"],
                    "pearson_p": st["pearson_p"],
                    "spearman_rho": st["spearman_rho"],
                    "spearman_p": st["spearman_p"],
                    "slope": st["slope"],
                    "intercept": st["intercept"],
                    "slope_se": st["slope_se"],
                    "r_squared": st["r_squared"],
                })

            block = valid[["county_fips", "county_name", "adult_pop",
                           label, "cert_count", "cert_rate"]].rename(
                columns={label: "ses_value"})
            long_rows.append(block.assign(condition=condition, domain=domain,
                                          measure=label, year=year))

            if year == primary_year:
                wide = valid.sort_values(label)[
                    ["county_name", "county_fips", "adult_pop",
                     label, "cert_count", "cert_rate"]
                ].copy()
                wide.columns = [
                    "County", "County FIPS", "Adult population (18+)", label,
                    f"{condition} certifications (count)",
                    f"{condition} cert rate (per {RATE_PER:,} adults)",
                ]
                per_measure[label] = wide

        print(f"  done: {label}")

    stats_df = pd.DataFrame(stats_rows)
    long_df = pd.concat(long_rows, ignore_index=True)[
        ["condition", "domain", "measure", "year", "county_fips", "county_name",
         "adult_pop", "ses_value", "cert_count", "cert_rate"]
    ]
    return stats_df, long_df, per_measure


def write_workbook(path, stats_df, long_df, per_measure):
    """Write the three-part workbook."""
    with pd.ExcelWriter(path, engine="openpyxl") as writer:
        stats_df.to_excel(writer, sheet_name="Stats_Summary", index=False)
        long_df.to_excel(writer, sheet_name="Combined_Long", index=False)
        for label, frame in per_measure.items():
            frame.to_excel(writer, sheet_name=sheet_name(label), index=False)


