#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
build_anxiety_dataset.py
========================
Analysis code of record for:

    "Sociodemographic Correlates of Medical Cannabis Certification for Anxiety
     Disorders Across Pennsylvania Counties, 2019-2024"

This single script reproduces the county-level analysis reported in the
manuscript. It builds one Excel workbook:

    Anxiety_Disorders_Results.xlsx
        Stats_Summary   - Pearson r, Spearman rho, and OLS regression estimates
                          for each of the 17 sociodemographic measures in each
                          study year (17 x 6 = 102 rows). This sheet is the
                          source of Table 1.
        Combined_Long   - the underlying county-level observations in long
                          format: one row per measure x year x county
                          (17 x 6 x 67 = 6,834 rows).
        <17 sheets>     - one wide sheet per measure for the primary year,
                          the form used to plot the manuscript figures.

No figures are produced. Figures 2-5 were drawn in GraphPad Prism from the
per-measure sheets of this workbook. Figure 1 (statewide certification counts,
condition shares, the county choropleth, and the comorbidity panels) was
produced separately and is not generated by this script.


WHAT THE SCRIPT DOES
--------------------
For every study year:

  1. Reads the Pennsylvania Department of Health medical cannabis
     certification record and keeps certifications that list anxiety disorders
     among the qualifying serious medical conditions (fields SMC1-SMC10).
  2. Allocates those certifications from five-digit ZIP code to county using
     the year-matched HUD USPS ZIP-County crosswalk residential ratio. For ZIP
     codes spanning county lines the ratios are renormalized to sum to 1 within
     each ZIP, and county totals are rounded to the nearest whole certification.
  3. Downloads the American Community Survey (ACS) 5-year estimates for all 67
     Pennsylvania counties from the Census Data API, using the ACS release with
     the same year as the certifications.
  4. Computes the certification rate per 1,000 adults aged 18 and over and the
     17 sociodemographic measures defined in MEASURES below.
  5. Fits county-level Pearson, Spearman, and ordinary least-squares models.

The 17 measures, their domains, and their ACS variable codes correspond exactly
to Table 1 of the manuscript and to Supplementary Table S2.


DATA AVAILABILITY
-----------------
Two of the three inputs are public and can be obtained by anyone:

  * ACS 5-year estimates - downloaded automatically by this script from
    https://api.census.gov/data/{year}/acs/acs5 . A free API key is required:
    https://api.census.gov/data/key_signup.html
  * HUD USPS ZIP-County crosswalk files - https://www.huduser.gov/apps/public/uspsutilities/
    (select ZIP-COUNTY, Pennsylvania, 4th quarter of each study year).

The third input, the individual-level certification record, was provided by the
Pennsylvania Department of Health under a data use agreement and cannot be
redistributed by the authors. It is available to other investigators through
application to the Department. The script reads only two fields from it - the
five-digit ZIP code and the qualifying-condition fields - and no direct or
indirect patient identifier is read, stored, or written at any point.

Because the certification record is restricted, the script includes a self-test
that verifies every calculation against small synthetic inputs with known
answers, requiring neither the restricted data nor an API key:

    python build_anxiety_dataset.py --selftest


INPUT FILES
-----------
Place these in one directory (the working directory by default):

    certifications(2019).csv ... certifications(2024).csv
        PA DOH certification record. Required columns: Zipcode, SMC1 ... SMC10.
    PA_HUD_ZIP_COUNTY_2019.csv ... PA_HUD_ZIP_COUNTY_2024.csv
        HUD crosswalk. Required columns: zip, county, res_ratio.


USAGE
-----
    export CENSUS_API_KEY=your_key_here        # Windows: set CENSUS_API_KEY=...
    python build_anxiety_dataset.py

    python build_anxiety_dataset.py --data-dir /path/to/data --out results.xlsx
    python build_anxiety_dataset.py --years 2019-2024 --primary-year 2024
    python build_anxiety_dataset.py --selftest        # verify the math, no data needed

Runtime is roughly two minutes, almost all of it reading the certification CSVs.


REQUIREMENTS
------------
    Python 3.9 or newer
    pandas >= 1.3   numpy >= 1.20   scipy >= 1.7   requests >= 2.25   openpyxl >= 3.0

    pip install "pandas>=1.3" "numpy>=1.20" "scipy>=1.7" "requests>=2.25" "openpyxl>=3.0"

The analysis is fully deterministic: no random number generation is involved,
and re-running the script on the same inputs reproduces the workbook exactly.

Portions of this script were drafted with the assistance of large language
models (Google Gemini 2.5 Flash; Anthropic Claude Opus 4.7, 4.8, and 5.0). All
code was manually inspected and verified by the authors before use.
"""

