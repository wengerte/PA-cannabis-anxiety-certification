def parse_years(text):
    """Accept '2019-2024' or '2019,2020,2021'."""
    if "-" in text:
        first, last = (int(p) for p in text.split("-", 1))
        return list(range(first, last + 1))
    return [int(p) for p in text.split(",") if p.strip()]


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Build the analytic dataset for the Pennsylvania medical "
                    "cannabis / anxiety disorders county-level study.")
    parser.add_argument("--data-dir", default=".",
                        help="Directory holding certifications(YYYY).csv and "
                             "PA_HUD_ZIP_COUNTY_YYYY.csv (default: current directory)")
    parser.add_argument("--out", default="Anxiety_Disorders_Results.xlsx",
                        help="Output workbook path")
    parser.add_argument("--api-key", default=os.environ.get("CENSUS_API_KEY"),
                        help="Census API key (default: CENSUS_API_KEY environment "
                             "variable). Free key: https://api.census.gov/data/key_signup.html")
    parser.add_argument("--years", type=parse_years, default=STUDY_YEARS,
                        help=f"Study years (default {STUDY_YEARS[0]}-{STUDY_YEARS[-1]})")
    parser.add_argument("--primary-year", type=int, default=PRIMARY_YEAR,
                        help=f"Year for the per-measure sheets (default {PRIMARY_YEAR})")
    parser.add_argument("--selftest", action="store_true",
                        help="Verify all calculations against synthetic inputs "
                             "and exit. Requires no data files and no API key.")
    args = parser.parse_args(argv)

    if args.selftest:
        return selftest()

    if not args.api_key:
        parser.error("A Census API key is required. Set the CENSUS_API_KEY "
                     "environment variable or pass --api-key. Request a free key "
                     "at https://api.census.gov/data/key_signup.html")

    if args.primary_year not in args.years:
        parser.error(f"--primary-year {args.primary_year} is not in "
                     f"--years {args.years}")

    missing = [f for year in args.years
               for f in (f"certifications({year}).csv",
                         f"PA_HUD_ZIP_COUNTY_{year}.csv")
               if not os.path.exists(os.path.join(args.data_dir, f))]
    if missing:
        print("ERROR: the following input files were not found in "
              f"{os.path.abspath(args.data_dir)}:", file=sys.stderr)
        for f in missing:
            print(f"  {f}", file=sys.stderr)
        print("\nThe certification record is restricted; see the DATA "
              "AVAILABILITY note at the top of this script. Run "
              "--selftest to verify the calculations without it.", file=sys.stderr)
        return 1

    stats_df, long_df, per_measure = build_dataset(
        args.data_dir, args.api_key, args.years, args.primary_year)

    write_workbook(args.out, stats_df, long_df, per_measure)

    print(f"\nWrote {os.path.abspath(args.out)}")
    print(f"  Stats_Summary   {len(stats_df):,} rows "
          f"({len(stats_df.measure.unique())} measures x {len(args.years)} years)")
    print(f"  Combined_Long   {len(long_df):,} rows")
    print(f"  Measure sheets  {len(per_measure)} ({args.primary_year})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
