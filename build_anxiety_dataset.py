CONDITION = "Anxiety Disorders"

# Study period. Anxiety disorders became a qualifying condition in Pennsylvania
# in 2019, so 2019 is the first year in which the condition can be certified.
STUDY_YEARS = [2019, 2020, 2021, 2022, 2023, 2024]

# Year used for the per-measure wide sheets and the manuscript scatter plots.
PRIMARY_YEAR = 2024

# Certification rate is expressed per this many adults aged 18 and over.
RATE_PER = 1000

PA_STATE_FIPS = "42"
ACS5_BASE = "https://api.census.gov/data/{year}/acs/acs5"

# Latest ACS 5-year release available at the time of analysis. Study years after
# this fall back to this release.
LATEST_ACS_RELEASE = 2024

# Census Bureau special values denoting a suppressed or non-applicable estimate.
# These are recoded as missing before any arithmetic is performed.
CENSUS_NULL = {-666666666, -999999999, -888888888, -222222222, -333333333}

# Minimum number of counties with non-missing data required to fit a model.
MIN_N_FOR_STATS = 5

# --- Adult population, ACS table B01001 --------------------------------------
# Denominator of the certification rate: males aged 18+ (B01001_007E through
# B01001_025E) plus females aged 18+ (B01001_031E through B01001_049E).
# These 38 cells are listed individually in Supplementary Table S2c.
ADULT_POP_VARS = (
    [f"B01001_{i:03d}E" for i in range(7, 26)]
    + [f"B01001_{i:03d}E" for i in range(31, 50)]
)

# --- The 17 sociodemographic measures ----------------------------------------
# Domains and measure order match Table 1 of the manuscript and Supplementary
# Table S2a exactly. Each measure is {"num": [numerator ACS variables],
# "den": denominator or None}. When "den" is set the measure is
# 100 * sum(num) / den; when "den" is None the ACS estimate is used directly
# (medians and per-capita dollar amounts).
MEASURES = {
    "Demographic": {
        "Median age (years)":
            {"num": ["B01002_001E"], "den": None},
        "Population 65 and over (%)":
            {"num": [f"B01001_{i:03d}E" for i in
                     list(range(20, 26)) + list(range(44, 50))],
             "den": "B01001_001E"},
        "White alone, not Hispanic/Latino (%)":
            {"num": ["B03002_003E"], "den": "B03002_001E"},
        "Black or African American (%)":
            {"num": ["B03002_004E"], "den": "B03002_001E"},
        "Hispanic or Latino, any race (%)":
            {"num": ["B03002_012E"], "den": "B03002_001E"},
        "Asian alone (%)":
            {"num": ["B03002_006E"], "den": "B03002_001E"},
    },
    "Income & socioeconomic": {
        "Median household income ($)":
            {"num": ["B19013_001E"], "den": None},
        "Per capita income ($)":
            {"num": ["B19301_001E"], "den": None},
        "Median gross rent ($)":
            {"num": ["B25064_001E"], "den": None},
        "Below poverty line (%)":
            {"num": ["B17001_002E"], "den": "B17001_001E"},
        "Households receiving SNAP (%)":
            {"num": ["B22003_002E"], "den": "B22003_001E"},
    },
    "Education": {
        # Universe for table B15003 is the population aged 25 and over.
        # The four reported categories partition B15003_017E-B15003_025E.
        # The remainder of the universe (B15003_002E-B15003_016E, less than a
        # high school diploma) was not reported in the manuscript and is not
        # computed here.
        "High school diploma or GED (%)":
            {"num": ["B15003_017E", "B15003_018E"], "den": "B15003_001E"},
        "Some college, no degree (%)":
            {"num": ["B15003_019E", "B15003_020E"], "den": "B15003_001E"},
        "Associate's degree (%)":
            {"num": ["B15003_021E"], "den": "B15003_001E"},
        "Bachelor's degree or higher (%)":
            {"num": ["B15003_022E", "B15003_023E", "B15003_024E", "B15003_025E"],
             "den": "B15003_001E"},
    },
    "Employment": {
        # Labor force participation is denominated by the population aged 16 and
        # over (B23025_001E). Unemployment is denominated by the civilian labor
        # force (B23025_003E), consistent with the standard BLS definition. The
        # two measures therefore use different denominators by design.
        "Labor force participation rate (%)":
            {"num": ["B23025_002E"], "den": "B23025_001E"},
        "Unemployment rate (%)":
            {"num": ["B23025_005E"], "den": "B23025_003E"},
    },
}

SMC_COLS = [f"SMC{i}" for i in range(1, 11)]


# =============================================================================
# CERTIFICATION RECORD
# =============================================================================

def fingerprint(s):
    """Normalize a condition name for matching.

    The Department of Health record spells the same condition slightly
    differently across years (curly vs. straight apostrophes, stray punctuation,
    inconsistent capitalization). Reducing each name to lowercase alphanumerics
    and spaces makes the match robust to those variations.
    """
    return re.sub(r"[^a-z0-9 ]", "", str(s).lower()).strip()


def load_certifications(path):
    """Read one year of the certification record into long format.

    Returns one row per (certification, listed condition), with columns
    cert_id, Zipcode, condition. Only the ZIP code and the ten qualifying-
    condition fields are read; all other columns are ignored.
    """
    wanted = ["Zipcode"] + SMC_COLS
    dtypes = {c: str for c in wanted}
    try:
        df = pd.read_csv(path, usecols=lambda c: c in wanted,
                         dtype=dtypes, low_memory=False, encoding="utf-8")
    except UnicodeDecodeError:
        df = pd.read_csv(path, usecols=lambda c: c in wanted,
                         dtype=dtypes, low_memory=False, encoding="cp1252")

    df["Zipcode"] = df["Zipcode"].str.strip().str.zfill(5)
    for col in SMC_COLS:
        if col in df.columns:
            df[col] = df[col].str.strip().replace("nan", pd.NA)

    # The row index is a stable within-year certification identifier. It is used
    # only to avoid double-counting a certification that lists the same
    # condition in more than one SMC field; it leaves the script with the file.
    df = df.reset_index().rename(columns={"index": "cert_id"})

    pieces = []
    for col in SMC_COLS:
        if col not in df.columns:
            continue
        valid = df[col].notna() & (df[col] != "") & (df[col] != "nan")
        if valid.any():
            sub = df.loc[valid, ["cert_id", "Zipcode"]].copy()
            sub["condition"] = df.loc[valid, col].values
            pieces.append(sub)

    return pd.concat(pieces, ignore_index=True) if pieces else pd.DataFrame(
        columns=["cert_id", "Zipcode", "condition"])


def county_cert_counts(cert_long, hud, condition):
    """Allocate certifications for one condition from ZIP code to county.

    Certifications are counted once per certification per ZIP code, then split
    across the counties a ZIP code overlaps in proportion to the HUD residential
    address ratio. Ratios are renormalized to sum to 1 within each ZIP code so
    that no certification is lost or duplicated when HUD ratios do not sum
    exactly to 1. County totals are rounded to the nearest whole certification,
    so county counts may not sum exactly to the statewide total.
    """
    target = fingerprint(condition)
    rows = cert_long[cert_long["condition"].map(fingerprint) == target]
    if rows.empty:
        return pd.DataFrame(columns=["county_fips", "cert_count"])

    zip_counts = (rows.groupby("Zipcode")["cert_id"].nunique()
                      .reset_index(name="cert_count"))

    merged = zip_counts.merge(hud[["zip", "county", "res_ratio"]],
                              left_on="Zipcode", right_on="zip", how="left")
    merged = merged.dropna(subset=["county"])

    ratio_sums = merged.groupby("Zipcode")["res_ratio"].transform("sum").replace(0, np.nan)
    merged["norm_ratio"] = (merged["res_ratio"] / ratio_sums).fillna(1.0)
    merged["weighted_certs"] = merged["cert_count"] * merged["norm_ratio"]

    out = (merged.groupby("county")["weighted_certs"].sum()
                 .round().astype(int).reset_index())
    out.columns = ["county_fips", "cert_count"]
    return out


def load_hud(path):
    """Read one year of the HUD USPS ZIP-County crosswalk."""
    df = pd.read_csv(path, dtype={"zip": str, "county": str})
    df["zip"] = df["zip"].str.strip().str.zfill(5)
    df["county"] = df["county"].str.strip().str.zfill(5)
    return df


# =============================================================================
# AMERICAN COMMUNITY SURVEY
# =============================================================================

def required_acs_vars():
    """Every ACS variable the analysis needs, deduplicated and sorted.

    This is the 66-variable list documented in Supplementary Table S2b: the 38
    adult-population cells plus the numerators and denominators of the 17
    measures, with duplicates removed.
    """
    needed = set(ADULT_POP_VARS)
    for measures in MEASURES.values():
        for cfg in measures.values():
            needed.update(cfg["num"])
            if cfg["den"]:
                needed.add(cfg["den"])
    return sorted(needed)


def fetch_acs(year, api_key, var_ids, chunk_size=45, session=None):
    """Download ACS 5-year estimates for all Pennsylvania counties.

    The Census API caps the number of variables per request, so the variable
    list is requested in chunks and joined on county FIPS code.
    """
    release = min(year, LATEST_ACS_RELEASE)
    session = session or requests.Session()
    frames = []

    for start in range(0, len(var_ids), chunk_size):
        chunk = var_ids[start:start + chunk_size]
        url = (f"{ACS5_BASE.format(year=release)}"
               f"?get={','.join(['NAME'] + chunk)}"
               f"&for=county:*&in=state:{PA_STATE_FIPS}&key={api_key}")
        resp = session.get(url, timeout=60)
        resp.raise_for_status()
        payload = resp.json()

        frame = pd.DataFrame(payload[1:], columns=payload[0])
        frame["county_fips"] = frame["state"] + frame["county"]
        for var in chunk:
            if var in frame.columns:
                frame[var] = pd.to_numeric(frame[var], errors="coerce")
                frame[var] = frame[var].where(~frame[var].isin(CENSUS_NULL))
        frames.append(frame)
        time.sleep(0.3)  # courtesy delay between API requests

    acs = frames[0]
    for extra in frames[1:]:
        new = [c for c in extra.columns if c not in acs.columns]
        acs = acs.merge(extra[["county_fips"] + new], on="county_fips", how="left")

    present = [v for v in ADULT_POP_VARS if v in acs.columns]
    acs["adult_pop"] = acs[present].sum(axis=1, min_count=1)
    acs["county_name"] = (acs["NAME"]
                          .str.replace(", Pennsylvania", "", regex=False)
                          .str.strip())
    return acs


def compute_measure(acs, cfg):
    """Compute one sociodemographic measure for every county.

    Percentage measures are 100 * sum(numerator variables) / denominator.
    Direct estimates (medians, per-capita income) are returned unchanged. A
    denominator of zero yields a missing value rather than an error.
    """
    nums = [v for v in cfg["num"] if v in acs.columns]
    if not nums:
        return pd.Series(np.nan, index=acs.index)

    numerator = acs[nums].sum(axis=1, min_count=1)
    if cfg["den"] and cfg["den"] in acs.columns:
        denominator = acs[cfg["den"]].replace(0, np.nan)
        return numerator / denominator * 100
    return numerator


# =============================================================================
# STATISTICS
# =============================================================================

def compute_stats(x, y):
    """County-level association between one measure (x) and the rate (y).

    Returns Pearson and Spearman correlations with their two-sided p-values,
    and OLS slope, intercept, standard error of the slope, and R-squared.
    Returns None when fewer than MIN_N_FOR_STATS counties have complete data.
    No correction for multiple comparisons is applied; see the Methods.
    """
    mask = ~np.isnan(x) & ~np.isnan(y)
    x, y = x[mask], y[mask]
    if len(x) < MIN_N_FOR_STATS:
        return None

    pearson_r, pearson_p = stats.pearsonr(x, y)
    spearman_rho, spearman_p = stats.spearmanr(x, y)
    slope, intercept, r_value, _, slope_se = stats.linregress(x, y)

    return {
        "n": int(len(x)),
        "pearson_r": pearson_r,
        "pearson_p": pearson_p,
        "spearman_rho": spearman_rho,
        "spearman_p": spearman_p,
        "slope": slope,
        "intercept": intercept,
        "slope_se": slope_se,
        "r_squared": r_value ** 2,
    }


